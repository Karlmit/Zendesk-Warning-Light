r"""Generate the PyInstaller version resource for ZendeskWarningLight.exe.

Without this the built exe has no version information at all: Windows shows a blank
Version in file Properties, and software inventory tools cannot identify it. The
single source of truth is ``zwl.__version__``.

    python tools\make_version_file.py [output_path]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "build" / "version_info.txt"

COMPANY = "Karl Almqvist"
PRODUCT = "Zendesk Warning Light"
DESCRIPTION = "Warns when a Zendesk ticket needs attention"
EXE_NAME = "ZendeskWarningLight.exe"

TEMPLATE = """# Generated by tools/make_version_file.py - do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tup},
    prodvers={tup},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', {company!r}),
         StringStruct('FileDescription', {description!r}),
         StringStruct('FileVersion', {version!r}),
         StringStruct('InternalName', {internal!r}),
         StringStruct('OriginalFilename', {exe!r}),
         StringStruct('ProductName', {product!r}),
         StringStruct('ProductVersion', {version!r})])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def read_version() -> str:
    text = (ROOT / "zwl" / "__init__.py").read_text(encoding="utf-8")
    match = re.search(r'__version__\s*=\s*"([^"]+)"', text)
    if not match:
        raise SystemExit("could not find __version__ in zwl/__init__.py")
    return match.group(1)


def version_tuple(version: str) -> tuple[int, int, int, int]:
    parts = [int(p) for p in re.findall(r"\d+", version)][:4]
    while len(parts) < 4:
        parts.append(0)
    return tuple(parts)  # type: ignore[return-value]


def main() -> int:
    version = read_version()
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        TEMPLATE.format(
            tup=version_tuple(version),
            company=COMPANY,
            description=DESCRIPTION,
            version=version,
            internal="ZendeskWarningLight",
            exe=EXE_NAME,
            product=PRODUCT,
        ),
        encoding="utf-8",
    )
    print("wrote {} for version {}".format(out, version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
